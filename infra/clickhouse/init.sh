#!/usr/bin/env bash
# Runs once on first start (docker-entrypoint-initdb.d): medallion databases and users.
set -euo pipefail
clickhouse-client --user "$CLICKHOUSE_USER" --password "$CLICKHOUSE_PASSWORD" --multiquery <<SQL
CREATE DATABASE IF NOT EXISTS bronze;
CREATE DATABASE IF NOT EXISTS silver;
CREATE DATABASE IF NOT EXISTS gold;

CREATE USER IF NOT EXISTS ${CLICKHOUSE_PIPELINE_USER} IDENTIFIED BY '${CLICKHOUSE_PIPELINE_PASSWORD}';
GRANT ALL ON bronze.* TO ${CLICKHOUSE_PIPELINE_USER};
GRANT ALL ON silver.* TO ${CLICKHOUSE_PIPELINE_USER};
GRANT ALL ON gold.* TO ${CLICKHOUSE_PIPELINE_USER};
GRANT S3 ON *.* TO ${CLICKHOUSE_PIPELINE_USER};
GRANT NAMED COLLECTION ON ksei_s3 TO ${CLICKHOUSE_PIPELINE_USER};

CREATE USER IF NOT EXISTS ${CLICKHOUSE_SUPERSET_USER} IDENTIFIED BY '${CLICKHOUSE_SUPERSET_PASSWORD}';
GRANT SELECT ON gold.* TO ${CLICKHOUSE_SUPERSET_USER};
SQL
